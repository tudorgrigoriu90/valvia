/**
 * Service worker generation (TS-05.3.2, NFR-03): after the build, every page, asset and the Pagefind index
 * are precached so the whole site and search work offline after the first visit. The worker version is a
 * hash of all file contents, so any content change installs a new cache.
 */
import { createHash } from 'node:crypto';

const EXCLUDED = /(^|\/)sw\.js$|\.map$/;

export function precacheUrls(files: readonly string[], base: string): string[] {
  return files
    .filter((file) => !EXCLUDED.test(file))
    .map((file) =>
      file === 'index.html' ? '' : file.endsWith('/index.html') ? file.slice(0, -'index.html'.length) : file,
    )
    .map((path) => `${base}${path}`);
}

export function versionOf(files: readonly (readonly [string, string])[]): string {
  const hash = createHash('sha256');
  for (const [name, content] of [...files].sort(([a], [b]) => a.localeCompare(b))) {
    hash.update(name).update('\0').update(content).update('\0');
  }
  return hash.digest('hex').slice(0, 12);
}

export function renderServiceWorker(urls: readonly string[], version: string, base: string): string {
  return `/* Generated by pipeline/pwa (TS-05.3.2). Do not edit. */
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(urls)};
const CACHE = 'valvia-' + VERSION;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('valvia-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (event) => {
  if (event.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;
  if (request.mode === 'navigate') {
    // Network first for pages so online users always get the latest content; cache when offline.
    event.respondWith(
      fetch(request).catch(() =>
        caches.match(url.pathname, { ignoreSearch: true }).then((hit) => hit || caches.match(BASE + '404.html')),
      ),
    );
    return;
  }
  event.respondWith(caches.match(request, { ignoreSearch: true }).then((hit) => hit || fetch(request)));
});
`;
}
